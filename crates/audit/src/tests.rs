use super::*;

#[test]
fn stored_names_match_the_serialized_ones() {
    for action in [
        Action::UserSignedIn,
        Action::UserSignInFailed,
        Action::UserSignedOut,
        Action::UserPasswordSet,
        Action::UserPasswordResetRequested,
        Action::UserInvited,
        Action::UserSecondStepEnabled,
        Action::UserSecondStepRemoved,
        Action::UserSecondStepReset,
        Action::UserRecoveryCodeUsed,
        Action::UserRecoveryCodesRegenerated,
        Action::ProjectCreated,
        Action::ProjectUpdated,
        Action::ProjectArchived,
        Action::ProjectRestored,
        Action::ProjectExported,
        Action::ProjectDuplicated,
        Action::MemberAdded,
        Action::MemberRoleChanged,
        Action::MemberRemoved,
        Action::DecisionCreated,
        Action::DecisionDeleted,
        Action::DecisionVersionSaved,
        Action::DecisionVersionRestored,
        Action::DecisionFindingAcknowledged,
        Action::ScenarioCreated,
        Action::ScenarioUpdated,
        Action::ScenarioDeleted,
        Action::ReleaseCreated,
        Action::ReleaseDeployed,
        Action::TokenIssued,
        Action::TokenRevoked,
        Action::ReleaseRolledBack,
        Action::ApprovalRequested,
        Action::ApprovalApproved,
        Action::ApprovalRejected,
        Action::ApprovalWithdrawn,
        Action::DecisionRecordExplained,
        Action::DecisionLogPurged,
        Action::DecisionLogResealed,
        Action::DecisionLogPeopleIndexed,
        Action::PersonRecordsSearched,
        Action::PersonReportExported,
        Action::PersonRecordsAnonymised,
        Action::RetentionRuleCreated,
        Action::RetentionRuleEnded,
        Action::DecisionContestOpened,
        Action::DecisionContestReviewed,
        Action::CiTokenIssued,
        Action::CiTokenRevoked,
    ] {
        assert_eq!(
            serde_json::to_value(action).unwrap(),
            Value::String(action.as_str().to_owned())
        );
    }
}
